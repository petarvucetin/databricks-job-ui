// Builds deploy/: a self-contained Databricks App (bundled server + built client + app.yaml, no package.json).
// With no package.json the platform skips `npm install`, which GovCloud apps can't do (no npm registry access).
import { execSync } from 'node:child_process';
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const run = (cmd: string) => execSync(cmd, { stdio: 'inherit' });

rmSync('deploy', { recursive: true, force: true });
run('npx tsc -b tsconfig.client.json');
run('npx vite build --config client/vite.config.ts');
run('npx tsdown -c tsdown.deploy.config.ts');
// public/ (one of AppKit's static folders), not client/dist: .gitignore's `dist/` would keep it out of git and the bundle upload.
cpSync('client/dist', 'deploy/public', { recursive: true });

// app.yaml is the single source for env settings; only the command changes, and production mode is pinned
// (without NODE_ENV=production AppKit would try to start Vite, which is not in the bundle).
const appYaml = readFileSync('app.yaml', 'utf8').replace(/\r\n/g, '\n');
if (!/^command:.*$/m.test(appYaml) || !/^env:\s*$/m.test(appYaml)) throw new Error('app.yaml needs a command: line and an env: block');
const out = appYaml
  .replace(/^command:.*$/m, "command: ['node', 'server.mjs']")
  .replace(/^env:\s*$/m, 'env:\n  - name: NODE_ENV\n    value: production');
writeFileSync(
  'deploy/app.yaml',
  '# Generated by `npm run package` from ../app.yaml. Edit that file and re-run, or edit here on a machine without Node.\n' + out,
);
writeFileSync(
  'deploy/README.md',
  '# jobs-console deploy folder\n\nGenerated by `npm run package`: bundled server (`server.mjs` + chunks), built client (`public`) and `app.yaml`.\nNo package.json on purpose: Databricks Apps then runs no `npm install`. Deploy with `databricks bundle deploy` from `jobs-console/`.\n',
);
if (!existsSync('deploy/server.mjs') || !existsSync('deploy/public/index.html')) throw new Error('deploy/ is incomplete');
console.log('deploy/ ready');
